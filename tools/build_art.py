def _attrs(attrs: dict) -> str:
    return "".join(f' {key.rstrip("_").replace("_", "-")}="{value}"' for key, value in attrs.items() if value is not None)


def rect(x, y, w, h, rx=0, **attrs) -> str:
    corner = f' rx="{num(rx)}"' if rx else ""
    return f'<rect x="{num(x)}" y="{num(y)}" width="{num(w)}" height="{num(h)}"{corner}{_attrs(attrs)}/>'


def circle(cx, cy, r, **attrs) -> str:
    return f'<circle cx="{num(cx)}" cy="{num(cy)}" r="{num(r)}"{_attrs(attrs)}/>'


def path(d: str, **attrs) -> str:
    return f'<path d="{d}"{_attrs(attrs)}/>'


def line(x1, y1, x2, y2, **attrs) -> str:
    return f'<line x1="{num(x1)}" y1="{num(y1)}" x2="{num(x2)}" y2="{num(y2)}"{_attrs(attrs)}/>'


def linear(gid: str, stops, x1="0", y1="0", x2="1", y2="0", user=False) -> str:
    """A linear gradient; stops: (offset, colour) or (offset, colour, opacity)."""
    units = ' gradientUnits="userSpaceOnUse"' if user else ""
    body = "".join(f'<stop offset="{s[0]}" stop-color="{s[1]}"' + (f' stop-opacity="{s[2]}"' if len(s) > 2 else "")
                   + "/>" for s in stops)
    return f'<linearGradient id="{gid}" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"{units}>{body}</linearGradient>'


def esc(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


class Doc:
    """An SVG document. Text is drawn as outlines: glyphs are defined once and placed with <use>, or inlined as one
    path per fill (inline=True: for gradient fills and for the logo files, which stay plain paths)."""

    def __init__(self, type_: Type, w: float, h: float, title: str, desc: str = ""):
        self.t, self.w, self.h, self.title, self.desc = type_, w, h, title, desc
        self.defs, self.body, self._glyphs, self._ids = [], [], {}, 0

    def uid(self, prefix: str) -> str:
        self._ids += 1
        return f"{prefix}{self._ids}"

    def add(self, *parts: str):
        self.body.extend(parts)

    def define(self, *parts: str):
        self.defs.extend(parts)

    def _glyph(self, weight, opsz, gid) -> str | None:
        key = (weight, opsz, gid)
        if key not in self._glyphs:
            self._glyphs[key] = (f"g{len(self._glyphs)}", self.t.outline(weight, opsz, gid))
        ref, outline = self._glyphs[key]
        return ref if outline else None

    def shape(self, text, size, weight=400, tracking=0.0, features=None) -> Shaped:
        return self.t.shape(text, size, weight, tracking, features)

    def measure(self, text, size, weight=400, tracking=0.0, features=None) -> float:
        return self.shape(text, size, weight, tracking, features).width if text else 0.0

    def bearing(self, text, size, weight=400) -> float:
        return self.t.bearing(text, size, weight) if text else 0.0

    def fit(self, text, size, max_w, weight=400) -> str:
        """The text, cut with an ellipsis to fit max_w, as Blender cuts a field."""
        if self.measure(text, size, weight) <= max_w:
            return text
        while text and self.measure(text.rstrip() + "…", size, weight) > max_w:
            text = text[:-1]
        return text.rstrip() + "…"

    def wrap(self, text, size, max_w, weight=400) -> list[str]:
        lines, current = [], ""
        for word in text.split():
            trial = f"{current} {word}".strip()
            if current and self.measure(trial, size, weight) > max_w:
                lines.append(current)
                current = word
            else:
                current = trial
        return lines + [current] if current else lines

    def text(self, x, y, text, size, weight=400, fill=TEXT, anchor="start", tracking=0.0, features=None,
             opacity=None, inline=False, fills=None) -> float:
        """Draw text with its baseline at y; returns its width. fills: ((end, fill), ...) colours the characters
        before each end with that fill, e.g. ((4, white), (7, gradient)) for "OpenAct"."""
        if not text:
            return 0.0
        run = self.shape(text, size, weight, tracking, features)
        if anchor == "middle":
            x -= run.width / 2
        elif anchor == "end":
            x -= run.width
        bands = fills or ((len(text), fill),)
        extra = f' opacity="{opacity}"' if opacity is not None else ""
        for index, (end, band_fill) in enumerate(bands):
            start = bands[index - 1][0] if index else 0
            glyphs = [g for g in run.glyphs if start <= g[3] < end]
            if inline:
                d = "".join(self.t.outline(run.weight, run.opsz, gid, run.k, x + gx * run.k, y - gy * run.k)
                            for gid, gx, gy, _cluster in glyphs)
                if d:
                    self.add(f'<path fill="{band_fill}"{extra} d="{d}"/>')
                continue
            uses = []
            for gid, gx, gy, _cluster in glyphs:
                ref = self._glyph(run.weight, run.opsz, gid)
                if ref is not None:
                    uses.append(f'<use href="#{ref}" x="{round(gx)}"' + (f' y="{round(gy)}"' if gy else "") + "/>")
            if uses:
                self.add(f'<g fill="{band_fill}"{extra} transform="translate({num(x)} {num(y)}) '
                         f'scale({run.k:.6g} {-run.k:.6g})">{"".join(uses)}</g>')
        return run.width

    def svg(self) -> str:
        glyphs = "".join(f'<path id="{ref}" d="{d}"/>' for ref, d in self._glyphs.values() if d)
        defs = "".join(self.defs) + glyphs
        head = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{num(self.w)}" height="{num(self.h)}" '
                f'viewBox="0 0 {num(self.w)} {num(self.h)}" role="img" aria-labelledby="title">')
        title = f'<title id="title">{esc(self.title)}</title>' + (f"<desc>{esc(self.desc)}</desc>" if self.desc else "")
        return GENERATED + head + title + (f"<defs>{defs}</defs>" if defs else "") + "".join(self.body) + "</svg>\n"


