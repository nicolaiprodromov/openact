def _clamp01(value: float) -> float:
    return min(1.0, max(0.0, value))


def biome_land(x: float, y: float) -> tuple[float, float, float, float]:
    """The land at (x, y), metres from its centre, east and north: (height in metres, temperature, moisture,
    altitude), the three Rules factors 0-1 as the demo's Map Range nodes give them. It is the demo's land(), with its
    mountain pointed, ridged and a metre taller, as a picture of a mountain needs: its top, above the 6 m the
    altitude factor spans, is rock and snow, above a belt of pines."""
    dx, dy = x - 5, y - 5
    profile, angle = math.exp(-(math.hypot(dx, dy) / 5.5) ** 1.4), math.atan2(dy, dx)
    ridges = 1 + (1 - profile ** 3) * (0.2 * math.sin(5 * angle + 1.3) + 0.09 * math.sin(9 * angle + 0.4))
    height = 7.0 * profile * ridges + 2.5 * math.exp(-((x + 6) ** 2 + (y - 7) ** 2) / 20)
    degrees, rain = 33.0 - 1.1 * (y + SPAN / 2) - 5.0 * height, 100.0 + 2800.0 * (x + SPAN / 2) / SPAN
    return height, _clamp01((degrees + 10) / 45), _clamp01(rain / 3000), _clamp01(height / 6)


def _band(value: float, edges) -> int:
    return sum(value >= edge for edge in edges[1:-1])


def biome_cell(factors, jitter) -> tuple[int, int, int]:
    """The cell a point reads: the band of each of its factors (temperature, moisture, altitude), jittered by
    (r - 0.5) Dither widths of its band as the node dithers (jitter: an r 0-1 per factor)."""
    bands = []
    for value, edges, r in zip(factors, (T_BANDS, THIRDS, THIRDS), jitter):
        b = _band(value, edges)
        bands.append(_band(_clamp01(value + (r - 0.5) * DITHER * (edges[b + 1] - edges[b])), edges))
    return tuple(bands)


def biome_plant(factors, jitter) -> int:
    """The plant of a point: its cell's outcome (biome_cell()) as the model reads biome_outcomes.csv: dry ground by
    temperature, then high ground, then the rest by temperature."""
    t, m, a = biome_cell(factors, jitter)
    if m == 0:
        return (6, 5, 4)[t]  # dry: heather on cold moors, olives on mild slopes, cacti in hot deserts
    return 0 if a == 2 else (1, 2, 3)[t]  # moderate or wet: pines up high, else birch, oak or palm by temperature


def biome_snow(height: float, temperature: float) -> float:
    """How much snow covers the ground, 0-1: the summit's, high and cold."""
    return _clamp01((height - 6.1) / 0.35) * _clamp01((0.3 - temperature) / 0.2)


def _rgb(colour: str) -> tuple:
    return tuple(int(colour[i:i + 2], 16) / 255 for i in (1, 3, 5))


def _hex(rgb) -> str:
    return "#" + "".join(f"{round(_clamp01(c) * 255):02X}" for c in rgb)


def _mix(a, b, t: float) -> tuple:
    return tuple(x + (y - x) * t for x, y in zip(a, b))


def _num1(value: float) -> str:
    """A coordinate to one decimal, without a trailing zero."""
    text = f"{value:.1f}".removesuffix(".0")
    return "0" if text == "-0" else text


def _poly(points, fill: str, grow: float = 0.0, **attrs) -> str:
    """A filled polygon. grow: pixels to push each corner out from the centre, so neighbouring facets overlap and no
    seam shows between them; to one decimal, as the terrain's hundreds of facets need no more."""
    if not grow:
        return path("M" + "L".join(f"{num(x)} {num(y)}" for x, y in points) + "Z", fill=fill, **attrs)
    mx, my = sum(x for x, _y in points) / len(points), sum(y for _x, y in points) / len(points)
    grown = []
    for x, y in points:
        far = math.hypot(x - mx, y - my) or 1.0
        grown.append((x + (x - mx) * grow / far, y + (y - my) * grow / far))
    return path("M" + "L".join(f"{_num1(x)} {_num1(y)}" for x, y in grown) + "Z", fill=fill, **attrs)


def _halves(cx, cy, rx, ry, sides=8) -> tuple[list, list]:
    """A low-poly ellipse as its left and right halves, split by the vertical through its centre: the left lit, the
    right in shade, as the whole banner is lit from the upper left."""
    ring = [(cx + rx * math.sin(math.tau * k / sides), cy - ry * math.cos(math.tau * k / sides))
            for k in range(sides + 1)]
    return ring[sides // 2:], ring[:sides // 2 + 1]


