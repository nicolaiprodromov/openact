LABEL_COLOURS = ("#9FB0C8", "#C8925A", "#6FCF97", "#D0647E")  # label rows 0-3 in the chips


def socket(doc: Doc, x, y, colour, shape="one"):
    if shape == "one":
        doc.add(circle(x, y, 6, fill=colour, stroke=OUTLINE, stroke_width=1.5))
        return
    doc.add(path(f"M{num(x)} {num(y - 7.5)}l7.5 7.5l-7.5 7.5l-7.5 -7.5z", fill=colour, stroke=OUTLINE,
                 stroke_width=1.5, stroke_linejoin="round"))
    if shape == "maybe":  # a field input that also takes a single value
        doc.add(circle(x, y, 1.9, fill=OUTLINE))


def check_icon(doc: Doc, x, y, colour, width=1.8):
    doc.add(path(f"M{num(x)} {num(y)}l3.6 3.6l7 -7", fill="none", stroke=colour, stroke_width=width,
                 stroke_linecap="round", stroke_linejoin="round"))


def chevron(doc: Doc, x, y, colour=TEXT_DIM):
    doc.add(path(f"M{num(x - 4)} {num(y - 2)}l4 4l4 -4", fill="none", stroke=colour, stroke_width=1.6,
                 stroke_linecap="round", stroke_linejoin="round"))


def field_box(doc: Doc, x, y, w, h=22):
    doc.add(rect(x, y, w, h, 5, fill=FIELD, stroke=FIELD_EDGE))


def draw_chip(doc: Doc, x, cy, colour, chip, dashed):
    kind = chip[0]
    if kind == "text":
        value, aside = chip[1], chip[2] if len(chip) > 2 else ""
        w = doc.measure(value, 12.5, 500, features={"tnum": True}) + 18
        if aside:
            w += doc.measure(aside, 12.5, 400) + 7
    elif kind in ("bars", "cells", "labels"):
        w = len(chip[1]) * PITCH - 2 + 16
    else:  # grid
        w = len(chip[1][0]) * 6.6 - 1.6 + 16
    doc.add(line(X0 + NW + 7, cy, x, cy, stroke=colour, stroke_width=2, stroke_opacity=".75",
                 stroke_dasharray="4 3.5" if dashed else None))
    doc.add(rect(x, cy - 11, w, 22, 6, fill="#1F2125", stroke=colour, stroke_opacity=".5"))
    if kind == "text":
        right = x + 9 + doc.text(x + 9, cy + 4.5, chip[1], 12.5, 500, fill="#F3F4F6", features={"tnum": True})
        if len(chip) > 2:
            doc.text(right + 7, cy + 4.5, chip[2], 12.5, 400, fill=TEXT_DIM)
    elif kind == "bars":
        for i, value in enumerate(chip[1]):
            h = max(2.0, value * 13)
            doc.add(rect(x + 8 + i * PITCH, cy + 6.5 - h, 6, h, 1.5, fill=colour))
    elif kind in ("cells", "labels"):
        for i, value in enumerate(chip[1]):
            cx = x + 8 + i * PITCH
            if kind == "labels":
                doc.add(rect(cx, cy - 3, 6, 6, 1.5, fill=LABEL_COLOURS[value]))
            elif value:
                doc.add(rect(cx, cy - 3, 6, 6, 1.5, fill=colour))
            else:
                doc.add(rect(cx + 0.5, cy - 2.5, 5, 5, 1.2, fill="none", stroke=colour, stroke_opacity=".55"))
    else:
        rows = chip[1]
        top = cy - (len(rows) * 6.6 - 1.6) / 2
        for r, bits in enumerate(rows):
            for c, bit in enumerate(bits):
                doc.add(rect(x + 8 + c * 6.6, top + r * 6.6, 5, 5, 1, fill=MINT if bit == "1" else "#3A3D45"))


def node_card(t: Type, key: str) -> Doc:
    title, group, rows = CARDS[key]
    section = {"out": 0, "seg": 1, "menu": 1, "check": 1, "status": 1}
    heights, gaps, last = [], [], None
    for row in rows:
        part = section.get(row[0], 2)
        gaps.append(6 if last is not None and part != last else 0)
        heights.append(26 if row[0] == "status" else ROW)
        last = part
    node_h = HEAD + 6 + sum(heights) + sum(gaps) + 8
    H = Y0 + node_h + 58
    alt = {"ask": "Ask answers one question with yes/no or an amount",
           "pick": "Pick chooses the entry of a list that best fits a prompt",
           "dials": "Dials turns one prompt into many named settings",
           "match": "Match asks one question about every item of a list",
           "classify": "Classify gives every item of a list one of several labels",
           "rules": "Rules decides each cell of a table of factors, and every element reads its cell"}[key]
    doc = Doc(t, W_CARD, H, f"The OpenAct {title} node", alt + ".")
    grid, clip, shadow = doc.uid("grid"), doc.uid("clip"), doc.uid("shadow")
    doc.define(
        f'<pattern id="{grid}" width="24" height="24" patternUnits="userSpaceOnUse">'
        f'{circle(12, 12, 1.1, fill=GRID_DOT)}</pattern>',
        f'<clipPath id="{clip}">{rect(0, 0, W_CARD, H, 16)}</clipPath>',
        f'<filter id="{shadow}" x="-15%" y="-10%" width="130%" height="125%">'
        f'<feDropShadow dx="0" dy="8" stdDeviation="10" flood-color="#000000" flood-opacity=".45"/></filter>',
    )
    doc.add(rect(0, 0, W_CARD, H, 16, fill=EDITOR), f'<g clip-path="url(#{clip})">',
            rect(0, 0, W_CARD, H, fill=f"url(#{grid})"), "</g>",
            rect(0.5, 0.5, W_CARD - 1, H - 1, 15.5, fill="none", stroke=EDITOR_EDGE))

    # where each row sits, for the links coming in from the left before the node is drawn over them
    centres, y = [], Y0 + HEAD + 6
    for row, h, gap in zip(rows, heights, gaps):
        y += gap
        centres.append(y + h / 2)
        y += h
    for row, cy in zip(rows, centres):
        if row[0] in ("csv", "input", "field") and row[-1] is True:
            colour = SOCKET["geometry" if row[0] == "csv" else row[2]]
            fade = doc.uid("fade")
            doc.define(linear(fade, ((0, colour, 0), (1, colour, 0.9)), "4", "0", num(X0), "0", user=True))
            doc.add(line(0, cy, X0, cy, stroke=f"url(#{fade})", stroke_width=2.2,
                         stroke_dasharray="4 3.5" if row[0] == "field" else None))

    doc.add(f'<g filter="url(#{shadow})">', rect(X0, Y0, NW, node_h, 9, fill=NODE, stroke=NODE_EDGE), "</g>")
    doc.add(rect(X0, Y0, NW, HEAD, 9, fill=HEADER), rect(X0, Y0 + HEAD - 10, NW, 10, fill=HEADER),
            line(X0, Y0 + HEAD, X0 + NW, Y0 + HEAD, stroke=NODE_EDGE, stroke_opacity=".7"))
    chevron(doc, X0 + 16, Y0 + HEAD / 2, "#D5D8DD")
    doc.text(X0 + 30, Y0 + 21, title, 14.5, 600, fill="#F2F3F5")
    gx, gy = X0 + NW - 24, Y0 + HEAD / 2  # the node group icon: the node wraps a hidden group
    doc.add(rect(gx - 7, gy - 5.5, 5, 5, 1, fill="none", stroke="#D5D8DD", stroke_width=1.2),
            rect(gx + 2, gy + 0.5, 5, 5, 1, fill="none", stroke="#D5D8DD", stroke_width=1.2),
            path(f"M{num(gx - 2)} {num(gy - 3)}h2.5v6h1.5", fill="none", stroke="#D5D8DD", stroke_width=1.2))

    left, right, chip_x = X0 + 16, X0 + NW - 14, X0 + NW + 24
    for row, cy in zip(rows, centres):
        kind = row[0]
        if kind == "out":
            _, label, sock, shape, chip = row
            doc.text(X0 + NW - 16, cy + 4.5, label, 13, 400, fill=TEXT, anchor="end")
            draw_chip(doc, chip_x, cy, SOCKET[sock], chip, shape == "field")
            socket(doc, X0 + NW, cy, SOCKET[sock], shape)
        elif kind == "seg":
            options, active = row[1], row[2]
            seg_clip, w = doc.uid("seg"), (right - (X0 + 14)) / len(options)
            doc.define(f'<clipPath id="{seg_clip}">{rect(X0 + 14, cy - 11, right - X0 - 14, 22, 5)}</clipPath>')
            doc.add(rect(X0 + 14, cy - 11, right - X0 - 14, 22, 5, fill=FIELD))
            doc.add(f'<g clip-path="url(#{seg_clip})">' + rect(X0 + 14 + active * w, cy - 11, w, 22, fill=ACTIVE)
                    + "</g>")
            for i in range(1, len(options)):
                if active not in (i - 1, i):
                    doc.add(line(X0 + 14 + i * w, cy - 11, X0 + 14 + i * w, cy + 11, stroke=FIELD_EDGE))
            doc.add(rect(X0 + 14, cy - 11, right - X0 - 14, 22, 5, fill="none", stroke=FIELD_EDGE))
            for i, option in enumerate(options):
                doc.text(X0 + 14 + (i + 0.5) * w, cy + 4.5, option, 12.5, 500 if i == active else 400,
                         fill="#FFFFFF" if i == active else "#C9CBD0", anchor="middle")
        elif kind == "menu":
            field_box(doc, X0 + 14, cy - 11, right - X0 - 14)
            doc.text(X0 + 24, cy + 4.5, row[1], 13, 400, fill="#E6E7EA")
            chevron(doc, right - 12, cy)
        elif kind == "check":
            doc.add(rect(X0 + 15, cy - 7, 14, 14, 3.5, fill=ACTIVE))
            check_icon(doc, X0 + 18.2, cy - 0.2, "#FFFFFF", 1.7)
            doc.text(X0 + 37, cy + 4.5, row[1], 13, 400, fill=TEXT)
        elif kind == "status":
            check_icon(doc, X0 + 16, cy, "#D3D6DB")
            doc.text(X0 + 36, cy + 4.5, row[1], 13, 400, fill="#D3D6DB")
        elif kind == "word":
            _, label, value = row
            socket(doc, X0, cy, SOCKET["string"])
            doc.text(left, cy + 4.5, label, 13, 400, fill=TEXT)
            fx = left + LABEL_W
            field_box(doc, fx, cy - 11, right - fx)
            if value:
                doc.text(fx + 8, cy + 4.5, doc.fit(value, 12.5, right - fx - 16), 12.5, 400, fill="#ECEDEF")
        elif kind in ("csv", "input"):  # a socket and its label, no value: a CSV companion, Geometry, the Trigger
            socket(doc, X0, cy, SOCKET["geometry" if kind == "csv" else row[2]])
            doc.text(left, cy + 4.5, row[1], 13, 400, fill=TEXT)
        elif kind == "block":
            _, label, sock, name = row
            socket(doc, X0, cy, SOCKET[sock])
            doc.text(left, cy + 4.5, label, 13, 400, fill=TEXT)
            fx = left + LABEL_W
            field_box(doc, fx, cy - 11, right - fx)
            if sock == "collection":
                doc.add(rect(fx + 8, cy - 5, 10, 10, 2, fill="none", stroke="#E8E8E8", stroke_width=1.4),
                        rect(fx + 11, cy - 2, 4, 4, 0.8, fill="#E8E8E8"))
            else:
                doc.add(path(f"M{num(fx + 8)} {num(cy - 4.5)}h11l-5.5 9.5z", fill="none", stroke=SOCKET["object"],
                             stroke_width=1.5, stroke_linejoin="round"))
            doc.text(fx + 25, cy + 4.5, name, 12.5, 400, fill="#ECEDEF")
        elif kind == "field":
            _, label, sock, _linked = row
            socket(doc, X0, cy, SOCKET[sock], "field")
            doc.text(left, cy + 4.5, label, 13, 400, fill=TEXT)
        elif kind in ("slider", "number"):
            _, label, value = row
            socket(doc, X0, cy, SOCKET["float" if kind == "slider" else "int"], "maybe" if kind == "slider" else "one")
            width = right - left
            field_box(doc, left, cy - 11, width)
            if kind == "slider" and value > 0:
                slider_clip = doc.uid("slider")
                doc.define(f'<clipPath id="{slider_clip}">{rect(left, cy - 11, width, 22, 5)}</clipPath>')
                doc.add(f'<g clip-path="url(#{slider_clip})">' + rect(left, cy - 11, width * value, 22, fill=ACTIVE,
                                                                     fill_opacity=".85") + "</g>")
            doc.text(left + 10, cy + 4.5, label, 13, 400, fill=TEXT)
            doc.text(right - 10, cy + 4.5, f"{value:.3f}" if kind == "slider" else value, 13, 400, fill="#ECEDEF",
                     anchor="end", features={"tnum": True})

    fy = Y0 + node_h + 36
    doc.text(24, fy, GROUPS[group].upper(), 10.5, 600, fill="#6F7580", tracking=0.1)
    x = W_CARD - 24
    x -= doc.measure("per element", 11.5, 400)
    doc.text(x, fy, "per element", 11.5, 400, fill="#868B95")
    socket(doc, x - 11, fy - 4, "#868B95", "field")
    x -= 30 + doc.measure("one value", 11.5, 400)
    doc.text(x, fy, "one value", 11.5, 400, fill="#868B95")
    doc.add(circle(x - 11, fy - 4, 5, fill="#868B95", stroke=OUTLINE, stroke_width=1.5))
    return doc


