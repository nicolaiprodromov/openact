def num(value: float) -> str:
    """A coordinate to two decimals, without trailing zeros."""
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


class _Outline(BasePen):
    """A glyph outline as SVG path data: in font units (y up) as integers, or placed on the canvas (k, dx, dy)."""

    def __init__(self, k: float | None = None, dx: float = 0.0, dy: float = 0.0):
        super().__init__(None)
        self.k, self.dx, self.dy, self.d = k, dx, dy, []

    def _xy(self, p) -> str:
        if self.k is None:
            return f"{round(p[0])} {round(p[1])}"
        return f"{num(self.dx + p[0] * self.k)} {num(self.dy - p[1] * self.k)}"

    def _moveTo(self, p):
        self.d.append("M" + self._xy(p))

    def _lineTo(self, p):
        self.d.append("L" + self._xy(p))

    def _curveToOne(self, a, b, c):
        self.d.append("C" + " ".join(map(self._xy, (a, b, c))))

    def _qCurveToOne(self, a, b):
        self.d.append("Q" + " ".join(map(self._xy, (a, b))))

    def _closePath(self):
        self.d.append("Z")


@dataclass
class Shaped:
    """A shaped run: glyphs as (glyph id, x, y, cluster) in font units from the origin; width in pixels."""

    glyphs: list
    width: float
    k: float  # pixels per font unit
    weight: float
    opsz: float


class Type:
    """Inter, shaped with HarfBuzz (kerning, contextual forms) at any weight and optical size."""

    def __init__(self, path: Path):
        font = TTFont(path)
        font.flavor = None  # WOFF2 to plain OpenType, which HarfBuzz reads
        data = io.BytesIO()
        font.save(data)
        self.face = hb.Face(data.getvalue())
        self.upem = self.face.upem
        self.axes = {axis.axisTag for axis in font["fvar"].axes} if "fvar" in font else set()
        self.version = font["name"].getDebugName(5)
        self._fonts, self._outlines = {}, {}

    def _font(self, weight: float, opsz: float):
        key = (weight, opsz)
        if key not in self._fonts:
            font = hb.Font(self.face)
            axes = {tag: value for tag, value in (("wght", weight), ("opsz", opsz)) if tag in self.axes}
            if axes:
                font.set_variations(axes)
            self._fonts[key] = font
        return self._fonts[key]

    def shape(self, text: str, size: float, weight: float = 400, tracking: float = 0.0, features=None) -> Shaped:
        """tracking: extra space between letters, in em."""
        opsz = max(14.0, min(32.0, size))  # Inter's optical size follows the pixel size, as CSS does
        buffer = hb.Buffer()
        buffer.add_str(text)
        buffer.guess_segment_properties()
        hb.shape(self._font(weight, opsz), buffer, {"kern": True, "liga": True, **(features or {})})
        extra, x, glyphs = tracking * self.upem, 0.0, []
        for info, pos in zip(buffer.glyph_infos, buffer.glyph_positions):
            glyphs.append((info.codepoint, x + pos.x_offset, pos.y_offset, info.cluster))
            x += pos.x_advance + extra
        if glyphs:
            x -= extra
        k = size / self.upem
        return Shaped(glyphs, x * k, k, weight, opsz)

    def bearing(self, text: str, size: float, weight: float = 400) -> float:
        """The first glyph's left side bearing in pixels: how far right of the pen its ink starts."""
        run = self.shape(text, size, weight)
        extents = self._font(run.weight, run.opsz).get_glyph_extents(run.glyphs[0][0])
        return (extents.x_bearing if extents else 0) * run.k

    def outline(self, weight: float, opsz: float, gid: int, k=None, dx=0.0, dy=0.0) -> str:
        key = (weight, opsz, gid)
        if k is None and key in self._outlines:
            return self._outlines[key]
        pen = _Outline(k, dx, dy)
        self._font(weight, opsz).draw_glyph_with_pen(gid, pen)
        path = "".join(pen.d)
        if k is None:
            self._outlines[key] = path
        return path


def find_inter(explicit: str | None) -> Path:
    """Inter.woff2 from --font, OPENACT_ART_FONT, or the newest Blender install found."""
    for candidate in (explicit, os.environ.get("OPENACT_ART_FONT")):
        if candidate:
            path = Path(candidate)
            if not path.is_file():
                raise SystemExit(f"Font not found: {path}")
            return path
    if sys.platform == "win32":
        roots = [Path(os.environ.get(var, "")) / "Blender Foundation" for var in ("ProgramFiles", "ProgramFiles(x86)")]
    elif sys.platform == "darwin":
        roots = [Path("/Applications/Blender.app/Contents/Resources")]
    else:
        roots = [Path("/usr/share/blender"), Path("/opt"), Path.home() / "blender", Path("/snap/blender/current")]
    found = []
    for root in roots:
        if root.is_dir():
            for pattern in ("*/datafiles/fonts/Inter.woff2", "*/*/datafiles/fonts/Inter.woff2"):
                found += root.glob(pattern)
    if not found:
        raise SystemExit("Inter.woff2 not found: install Blender 4.5 or newer, or pass --font")

    def version(path: Path):  # .../5.1/datafiles/fonts/Inter.woff2 -> (5, 1)
        parts = path.parents[2].name.split(".")
        return tuple(int(p) for p in parts if p.isdigit())

    return max(found, key=version)


