def _cubic(p0, p1, p2, p3, t: float) -> tuple:
    """The point at t of a cubic Bézier curve."""
    u = 1 - t
    return tuple(u * u * u * a + 3 * u * u * t * b + 3 * u * t * t * c + t * t * t * d
                 for a, b, c, d in zip(p0, p1, p2, p3))


