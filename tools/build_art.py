def draw_wordmark(doc: Doc, x: float, baseline: float, size: float, dark: bool, inline: bool = True) -> float:
    """The wordmark at font size `size`, the O's visual left edge at x; returns the right edge of its advance."""
    x -= doc.bearing("OpenAct", size, 700)
    width = doc.text(x, baseline, "OpenAct", size, 700, tracking=-0.012, inline=inline,
                     fills=((4, PAPER if dark else INK), (7, CYAN if dark else CYAN_DEEP)))
    return x + width


