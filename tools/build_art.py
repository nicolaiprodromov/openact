def palette(t: Type) -> Doc:
    W, H, margin, gap = 880, 178, 28, 16
    doc = Doc(t, W, H, "OpenAct colours", ", ".join(f"{name} {colour}" for name, colour, _role in PALETTE) + ".")
    doc.add(rect(0, 0, W, H, 18, fill=EDITOR),
            rect(0.5, 0.5, W - 1, H - 1, 17.5, fill="none", stroke=EDITOR_EDGE))
    width = (W - 2 * margin - (len(PALETTE) - 1) * gap) / len(PALETTE)
    for i, (name, colour, role) in enumerate(PALETTE):
        x = margin + i * (width + gap)
        doc.add(rect(x, 28, width, 72, 12, fill=colour, stroke="#FFFFFF", stroke_opacity=".14"))
        doc.text(x + 2, 126, name, 14, 600, fill=PAPER)
        doc.text(x + 2, 146, colour.upper(), 12.5, 400, fill=MUTED, features={"tnum": True})
        doc.text(x + 2, 164, role, 11.5, 400, fill=FAINT)
    return doc


def logo_files(t: Type) -> dict[str, Doc]:
    docs = {}
    for dark in (True, False):  # 72 px type: the cap height and the p's descender, with room around them
        doc = Doc(t, 400, 104, "OpenAct")
        right = draw_wordmark(doc, 16, 70, 72, dark)
        doc.w = round(right + 16)
        docs[f"branding/openact-logo-{'dark' if dark else 'light'}.svg"] = doc
    docs["branding/palette.svg"] = palette(t)
    return docs


