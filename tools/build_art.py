def build(font: Path) -> list[Path]:
    t = Type(font)
    docs = logo_files(t)
    docs["docs/assets/banner.svg"] = banner(t)
    for key in CARDS:
        docs[f"docs/assets/nodes/{key}.svg"] = node_card(t, key)
    docs["docs/assets/roadmap.svg"] = roadmap(t)
    written = []
    for relative, doc in docs.items():
        target = ROOT / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(doc.svg(), encoding="utf-8", newline="\n")
        written.append(target)
    return written


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--font", help="Inter.woff2 or .ttf (default: from a Blender install)")
    args = parser.parse_args(argv)
    font = find_inter(args.font)
    print(f"Inter: {font}")
    for target in build(font):
        print(f"  {target.relative_to(ROOT).as_posix():36} {target.stat().st_size / 1024:6.1f} KB")


if __name__ == "__main__":
    main()
